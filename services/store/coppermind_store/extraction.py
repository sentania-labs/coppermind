"""Text extraction for artifacts, run in a resource-limited subprocess.

An artifact's bytes are whatever was handed in: a deck, a PDF, a document a
colleague exported. The parsers that read them are large libraries fed
untrusted input, so every extraction runs in its own process with an
address-space ceiling and a CPU budget, the same shape the calendar worker
uses. A parser that blows up, loops or allocates without bound takes down the
subprocess and the artifact is recorded as `failed`, with its bytes stored and
searchable by title; the store itself is never the process that pays.

`EXTRACTOR_VERSION` names the extraction rules. It is recorded on every
artifact record, and a record carrying another version is regenerated by the
next pass, which is how a better extractor reaches the artifacts already
stored without anyone re-uploading them.
"""

from __future__ import annotations

import json
import resource
import subprocess
import sys
from pathlib import Path
from typing import Any

from coppermind.store_protocol import ArtifactTextStatus

# Bump when the rules below change in a way that produces different text.
EXTRACTOR_VERSION = "1"

# Address space and CPU for one extraction. A deck of a few hundred slides or
# a long PDF fits in far less; the ceiling is for a parser that misbehaves.
MEMORY_MIB = 1024
CPU_SECONDS = 60
WALL_SECONDS = 90

# How much text one record keeps. The search index itself takes a quarter of a
# million characters; the record holds more so an agent reading the artifact
# through the API gets the whole of an ordinary document.
MAX_TEXT_CHARS = 2_000_000

PDF_TYPES = {"application/pdf", "application/x-pdf"}
PPTX_TYPES = {"application/vnd.openxmlformats-officedocument.presentationml.presentation"}
DOCX_TYPES = {"application/vnd.openxmlformats-officedocument.wordprocessingml.document"}
TEXT_TYPES = {"application/json", "application/xml", "application/x-yaml", "application/yaml"}

EXTENSION_TYPES = {
    ".pdf": "application/pdf",
    ".pptx": "application/vnd.openxmlformats-officedocument.presentationml.presentation",
    ".docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    ".txt": "text/plain",
    ".md": "text/markdown",
    ".markdown": "text/markdown",
    ".csv": "text/csv",
    ".json": "application/json",
    ".xml": "application/xml",
    ".yaml": "application/x-yaml",
    ".yml": "application/x-yaml",
    ".html": "text/html",
    ".htm": "text/html",
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".gif": "image/gif",
    ".webp": "image/webp",
    ".svg": "image/svg+xml",
    ".mp4": "video/mp4",
    ".mov": "video/quicktime",
    ".m4a": "audio/mp4",
    ".mp3": "audio/mpeg",
    ".wav": "audio/wav",
    ".zip": "application/zip",
}


def media_type(filename: str, declared: str | None, data: bytes) -> str:
    """The media type recorded for an upload: declared, else sniffed, else the extension."""
    if declared and declared != "application/octet-stream":
        return declared.partition(";")[0].strip().lower()
    if data.startswith(b"%PDF"):
        return "application/pdf"
    suffix = Path(filename).suffix.lower()
    if data.startswith(b"PK\x03\x04") and suffix in {".pptx", ".docx"}:
        return EXTENSION_TYPES[suffix]
    return EXTENSION_TYPES.get(suffix, "application/octet-stream")


def extractable(mime_type: str) -> bool:
    """Whether the extractor has a parser for this media type at all."""
    base = mime_type.partition(";")[0].strip().lower()
    return (
        base in PDF_TYPES
        or base in PPTX_TYPES
        or base in DOCX_TYPES
        or base in TEXT_TYPES
        or base.startswith("text/")
    )


def extract(path: Path, mime_type: str) -> tuple[str, ArtifactTextStatus]:
    """The artifact's text and how it was obtained, never raising.

    Runs the parser in a bounded subprocess. A type nothing here can read is
    `unsupported` without starting one; a readable type that yields no text,
    an image-only PDF say, is `no_extractable_text`; a parser that fails or
    exceeds its budget is `failed`.
    """
    if not extractable(mime_type):
        return "", "unsupported"
    payload = {"path": str(path), "mime_type": mime_type}
    try:
        result = subprocess.run(
            [sys.executable, "-m", "coppermind_store.extraction", str(MEMORY_MIB)],
            input=json.dumps(payload).encode(),
            capture_output=True,
            timeout=WALL_SECONDS,
            check=False,
        )
    except (subprocess.TimeoutExpired, OSError):
        return "", "failed"
    if result.returncode:
        return "", "failed"
    try:
        body = json.loads(result.stdout)
    except ValueError:
        return "", "failed"
    if body.get("error"):
        return "", "failed"
    text = str(body.get("text", ""))
    return text, ("extracted" if text.strip() else "no_extractable_text")


def _read_text(data: bytes) -> str:
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        return data.decode("utf-8", errors="replace")


def _pdf_text(path: Path) -> str:
    from pypdf import PdfReader

    reader = PdfReader(str(path))
    if reader.is_encrypted:
        try:
            reader.decrypt("")
        except Exception:  # noqa: BLE001 - an encrypted PDF simply has no readable text
            return ""
    pages = []
    for page in reader.pages:
        pages.append(page.extract_text() or "")
        if sum(len(item) for item in pages) > MAX_TEXT_CHARS:
            break
    return "\n\n".join(item.strip() for item in pages if item.strip())


def _pptx_text(path: Path) -> str:
    from pptx import Presentation

    presentation = Presentation(str(path))
    slides = []
    for number, slide in enumerate(presentation.slides, 1):
        lines = []
        for shape in slide.shapes:
            if getattr(shape, "has_text_frame", False) and shape.text_frame is not None:
                text = shape.text_frame.text.strip()
                if text:
                    lines.append(text)
            if getattr(shape, "has_table", False):
                for row in shape.table.rows:
                    cells = [cell.text.strip() for cell in row.cells if cell.text.strip()]
                    if cells:
                        lines.append(" | ".join(cells))
        notes = slide.notes_slide if slide.has_notes_slide else None
        if notes is not None and notes.notes_text_frame is not None:
            text = notes.notes_text_frame.text.strip()
            if text:
                lines.append(text)
        if lines:
            slides.append(f"Slide {number}\n" + "\n".join(lines))
        if sum(len(item) for item in slides) > MAX_TEXT_CHARS:
            break
    return "\n\n".join(slides)


def _docx_text(path: Path) -> str:
    import docx

    document = docx.Document(str(path))
    parts = [paragraph.text.strip() for paragraph in document.paragraphs if paragraph.text.strip()]
    for table in document.tables:
        for row in table.rows:
            cells = [cell.text.strip() for cell in row.cells if cell.text.strip()]
            if cells:
                parts.append(" | ".join(cells))
        if sum(len(item) for item in parts) > MAX_TEXT_CHARS:
            break
    return "\n".join(parts)


def _extract_in_process(path: Path, mime_type: str) -> str:
    base = mime_type.partition(";")[0].strip().lower()
    if base in PDF_TYPES:
        return _pdf_text(path)
    if base in PPTX_TYPES:
        return _pptx_text(path)
    if base in DOCX_TYPES:
        return _docx_text(path)
    return _read_text(path.read_bytes())


def main() -> None:
    memory_mib = int(sys.argv[1]) if len(sys.argv) > 1 else MEMORY_MIB
    memory_bytes = memory_mib * 1024**2
    resource.setrlimit(resource.RLIMIT_AS, (memory_bytes, memory_bytes))
    resource.setrlimit(resource.RLIMIT_CPU, (CPU_SECONDS, CPU_SECONDS))
    try:
        payload: dict[str, Any] = json.load(sys.stdin)
        text = _extract_in_process(Path(payload["path"]), str(payload["mime_type"]))
        text = text.replace("\x00", "")[:MAX_TEXT_CHARS]
        print(json.dumps({"text": text}))
    except MemoryError:
        print(json.dumps({"error": "extraction exceeded its memory budget"}))
    except Exception:  # noqa: BLE001 - parser errors can quote the document, so say only that it failed
        print(json.dumps({"error": "extraction failed"}))


if __name__ == "__main__":
    main()
